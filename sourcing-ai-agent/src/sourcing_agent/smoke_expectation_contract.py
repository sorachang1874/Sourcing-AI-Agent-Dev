def unknown_smoke_expectation_keys(expectations: dict[str, object] | None) -> list[str]:
    return sorted(
        key
        for key in (str(item or "").strip() for item in dict(expectations or {}))
        if key and key not in SUPPORTED_SMOKE_EXPECTATION_KEYS
    )


def validate_smoke_expectations(expectations: dict[str, object] | None, *, context: str = "expectations") -> list[str]:
    return [f"{context}:unknown_expectation:{key}" for key in unknown_smoke_expectation_keys(expectations)]
